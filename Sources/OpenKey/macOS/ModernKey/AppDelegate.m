//The window that gets the permissions granted, then starts the keyboard hook on its own.
-(void)showPermissionWindow {
    if (_permissionWC == nil) {
        _permissionWC = [[PermissionWindowController alloc] initWithReadyHandler:^{
            [self keyboardHookDidStart];
        }];
    }
    [_permissionWC present];
}

//Starts the keyboard hook if the permissions are there, otherwise asks for them.
-(void)startKeyboardHook {
    if ([AppPermissions allGranted] && [OpenKeyManager initEventTap]) {
        [self keyboardHookDidStart];
    } else {
        [self showPermissionWindow];
    }
}

-(void)keyboardHookDidStart {
    [self setQuickConvertString]; //also takes the "permission needed" notice off the menu
}

- (void)applicationDidFinishLaunching:(NSNotification *)aNotification {
    appDelegate = self;
    
    [LegacyOpenKey importSettingsIfNeeded];
    [SuggestionController registerDefaults]; //the Settings window may show them before the suggestion bar starts
    
    [self registerSupportedNotification];
    
    //set quick tooltip
    [[NSUserDefaults standardUserDefaults] setObject: [NSNumber numberWithInt: 50]
                                              forKey: @"NSInitialToolTipDelay"];
    
    //check whether this app has been launched before that or not
    //Only check instances owned by current user (for multi-user/Fast User Switching support)
    uid_t currentUID = getuid();
    NSArray<NSRunningApplication *>* runningApps = [[NSWorkspace sharedWorkspace] runningApplications];
    pid_t myPID = [[NSProcessInfo processInfo] processIdentifier];
    BOOL alreadyRunning = NO;

    for (NSRunningApplication *app in runningApps) {
        if ([app.bundleIdentifier isEqualToString:OPENKEY_BUNDLE] &&
            app.processIdentifier != myPID) {
            pid_t pid = app.processIdentifier;
            struct proc_bsdinfo proc;
            int size = proc_pidinfo(pid, PROC_PIDTBSDINFO, 0, &proc, sizeof(proc));
            if (size == sizeof(proc) && proc.pbi_uid == currentUID) {
                alreadyRunning = YES;
                break;
            }
        }
    }

    if (alreadyRunning) {
        [NSApp terminate:nil];
        return;
    }
    
    vShowIconOnDock = (int)[[NSUserDefaults standardUserDefaults] integerForKey:@"vShowIconOnDock"];
    if (vShowIconOnDock)
        [NSApp setActivationPolicy: NSApplicationActivationPolicyRegular];
    
    if (vSwitchKeyStatus & 0x8000)
        NSBeep();

    _statusMenu = [[StatusMenuController alloc] init];
    [self fillData]; //the engine starts from what was saved: language, typing method, code table, shortcut
    
    //init
    dispatch_async(dispatch_get_main_queue(), ^{
        [LegacyOpenKey resolveConflictIfRunning];
        [self startKeyboardHook];
        
        NSInteger showui = [[NSUserDefaults standardUserDefaults] integerForKey:@"ShowUIOnStartup"];
        if (showui == 1) {
            [self onControlPanelSelected];
        }
        [self setQuickConvertString];
    });
    
    //load default config if is first launch
    if ([[NSUserDefaults standardUserDefaults] boolForKey:@"NonFirstTime"] == 0) {
        [self loadDefaultConfig];
    }
    [[NSUserDefaults standardUserDefaults] setInteger:1 forKey:@"NonFirstTime"];
    
    //check update if enable
    NSInteger dontCheckUpdate = [[NSUserDefaults standardUserDefaults] integerForKey:@"DontCheckUpdate"];
    if (!dontCheckUpdate)
        [OpenKeyManager checkNewVersion:nil callbackFunc:nil];
    
    //correct run on startup
    NSInteger val = [[NSUserDefaults standardUserDefaults] integerForKey:@"RunOnStartup"];
    [appDelegate setRunOnStartup:val];
}

